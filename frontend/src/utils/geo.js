// Helper to resolve city coordinates strictly within India
export function getCoords(cityName, id = 0) {
    if (!cityName || cityName.trim().toLowerCase() === 'n/a' || cityName.trim().toLowerCase() === 'null') {
        const offsetLat = ((id * 31) % 7 - 3) * 0.04;
        const offsetLng = ((id * 47) % 7 - 3) * 0.04;
        return [28.6139 + offsetLat, 77.2090 + offsetLng];
    }
    
    const key = cityName.toLowerCase().trim().replace(/[,.-]/g, '');
    
    // Direct match
    if (CITY_COORDINATES[key]) {
        const [lat, lng] = CITY_COORDINATES[key];
        const offset = ((id * 37) % 100) * 0.0004;
        return [lat + offset, lng + offset];
    }

    // Partial match
    for (const [cityKey, coords] of Object.entries(CITY_COORDINATES)) {
        if (key.includes(cityKey) || cityKey.includes(key)) {
            const [lat, lng] = coords;
            const offset = ((id * 37) % 100) * 0.0004;
            return [lat + offset, lng + offset];
        }
    }

    // Fallback within India
    let hash = 0;
    for (let i = 0; i < key.length; i++) hash = (hash << 5) - hash + key.charCodeAt(i);
    const lat = 12.0 + (Math.abs(hash) % 17) + ((id % 10) * 0.02);
    const lng = 74.0 + (Math.abs(hash >> 3) % 12) + ((id % 10) * 0.02);
    return [lat, lng];
}

// Haversine formula to compute great-circle distance in Kilometers
export function calculateDistanceKm(cityA, cityB, idA = 0, idB = 1) {
    if (!cityA || !cityB) return null;
    const normA = cityA.trim().toLowerCase();
    const normB = cityB.trim().toLowerCase();
    
    // Same exact city name -> local intra-city distance (~2-8 km)
    if (normA === normB && normA !== 'n/a') {
        return Math.round((2.5 + ((idA + idB) % 6) * 0.8) * 10) / 10;
    }

    const [lat1, lon1] = getCoords(cityA, idA);
    const [lat2, lon2] = getCoords(cityB, idB);

    const R = 6371; // Earth's mean radius in km
    const dLat = (lat2 - lat1) * Math.PI / 180;
    const dLon = (lon2 - lon1) * Math.PI / 180;
    const a =
        Math.sin(dLat / 2) * Math.sin(dLat / 2) +
        Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
        Math.sin(dLon / 2) * Math.sin(dLon / 2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    const dist = R * c;

    return Math.round(dist * 10) / 10;
}

// User-friendly formatted distance string
export function formatDistance(km) {
    if (km === null || km === undefined || isNaN(km)) return 'Distance N/A';
    if (km < 1) return '< 1 km (Local Area)';
    if (km < 10) return `${km} km (Nearby)`;
    if (km < 50) return `${km} km (Same Metro)`;
    return `${km.toLocaleString()} km`;
}

// Estimated transit/drive time based on distance
export function estimateTransitTime(km) {
    if (km === null || km === undefined || isNaN(km)) return 'ETA N/A';
    if (km <= 5) return '~15-25 mins';
    if (km <= 15) return '~30-45 mins';
    if (km <= 40) return '~1-1.5 hrs';
    if (km <= 100) return '~2-3 hrs';
    const hrs = Math.round(km / 55);
    return `~${hrs} hrs`;
}
